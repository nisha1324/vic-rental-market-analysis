"""Run the data audit and write results/DATA_AUDIT.md.

    python scripts/download_data.py
    python scripts/audit.py

Exits non-zero if a hard check fails (a published figure doesn't match, a
total is inconsistent, a value is impossible), so it can gate the analysis.
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import pandas as pd  # noqa: E402

from rentals import audit, parse  # noqa: E402
from scripts.build import RAW, SOURCES, load_all  # noqa: E402

OUT = ROOT / "results" / "DATA_AUDIT.md"
TABLES = RAW / "rental_report_tables_sep2025.xlsx"


def md(df: pd.DataFrame) -> str:
    return df.to_markdown(index=False)


def fmt_jumps(df: pd.DataFrame) -> pd.DataFrame:
    return df.assign(quarter=df["quarter"].dt.strftime("%b %Y"),
                     change=(100 * df["change"]).round(1).astype(str) + "%")


def main() -> None:
    data = load_all()
    suburbs, lgas, aff = data["suburb_rents.csv"], data["lga_rents.csv"], data["lga_affordability.csv"]
    table4 = parse.parse_table4(TABLES)

    cov_sub = audit.coverage(suburbs, "suburb", "median_rent", ("suburb",))
    cov_lga = audit.coverage(lgas, "lga", "median_rent", ("lga",))
    cov_aff = audit.coverage(aff, "lga", "affordable_share", ("lga",))
    recon = audit.reconcile_table4(suburbs, table4)
    groups = audit.group_totals(suburbs)
    lga_tot = audit.lga_totals(lgas)
    aff_tot = audit.affordability_totals(aff)
    plaus = audit.plausibility(suburbs, lgas)
    jumps = audit.median_jumps(suburbs)
    small_jumps = audit.median_jumps(suburbs, min_lettings=10)
    largest_move = audit.median_jumps(suburbs, threshold=0)["change"].abs().max()
    small = audit.small_samples(suburbs)
    raw = set().union(*(parse.raw_labels(RAW / f) for _, f in SOURCES.values()), parse.raw_labels(TABLES))
    fixes = audit.name_fixes_used(raw)

    hard = {
        "Table 4: every published figure matches the parsed median": bool(recon["matches"].all()),
        "Table 4: every entry really is in the top/bottom of its group": bool(recon["rank_ok"].all()),
        "Suburbs: no Group Total below the sum of its suburbs": groups["total_below_sum"] == 0,
        "Suburbs: every gap is explained by a suppressed suburb": groups["gap_without_suppressed_suburb"] == 0,
        "LGAs: Victoria row = sum of regional Group Totals in every quarter":
            lga_tot["victoria_eq_group_totals"] == lga_tot["quarters"],
        "LGAs: Victoria never below the published LGAs; every gap has a suppressed LGA":
            lga_tot["victoria_below_lga_sum"] == 0 and lga_tot["gap_without_suppressed_lga"] == 0,
        "Affordability: Victoria row = sum of LGAs in every quarter": aff_tot["victoria_eq_lga_sum"] == aff_tot["quarters"],
        "Affordability: every share is between 0 and 1": aff_tot["share_out_of_range"] == 0,
        "No zero/negative medians or negative counts": all(
            plaus[k] == 0 for k in plaus if "nonpositive" in k or "negative" in k),
        "No median published without a count": all(plaus[k] == 0 for k in plaus if "without" in k),
        "No missing quarters inside any series": int(
            pd.concat([cov_sub, cov_lga, cov_aff])["missing_quarters"].sum()) == 0,
    }

    latest = suburbs["quarter"].max()
    lines = [
        "# Data audit",
        "",
        "Generated by `scripts/audit.py` from the four Homes Victoria workbooks "
        "(see `scripts/download_data.py` for sources and checksums). Don't edit by hand.",
        "",
        "## Hard checks",
        "",
        "| Check | Result |",
        "|---|---|",
        *[f"| {name} | {'pass' if ok else '**FAIL**'} |" for name, ok in hard.items()],
        "",
        "## 1. Moving annual rents by suburb",
        "",
        "Median weekly rent of new leases that started in the 12 months ending each quarter, "
        f"for {suburbs.loc[suburbs.row_type == 'suburb', 'suburb'].nunique()} suburbs and towns "
        f"({suburbs.loc[(suburbs.row_type == 'suburb') & suburbs.metro, 'suburb'].nunique()} in metropolitan "
        f"Melbourne, {suburbs.loc[(suburbs.row_type == 'suburb') & ~suburbs.metro, 'suburb'].nunique()} regional) "
        f"in {suburbs['region'].nunique()} regions. `missing_pct` is the share of suburb-quarters "
        "with no published median (suppressed with '-', or the suburb had no series yet).",
        "",
        md(cov_sub),
        "",
        f"**Small samples in the latest quarter ({latest:%b %Y}).** Medians resting on fewer than 30 "
        "new leases in the year. The analysis should rank on the larger dwelling types or flag these.",
        "",
        md(small),
        "",
        "## 2. Quarterly median rents by Local Government Area",
        "",
        "Median weekly rent of new leases that started in that quarter alone (noisier than the "
        f"moving annual series), for {lgas.loc[lgas.row_type == 'lga', 'lga'].nunique()} LGAs.",
        "",
        md(cov_lga),
        "",
        "## 3. Affordable lettings by LGA",
        "",
        "Share of new leases affordable to a lower-income household on Centrelink payments "
        "(rent at most 30% of gross income), by bedroom count. The latest copy that can be fetched "
        "without a browser is the September 2024 workbook, so this series stops a year earlier "
        "than the rents.",
        "",
        md(cov_aff),
        "",
        "## Reconciliation with the published report (Table 4)",
        "",
        f"Table 4 of the {latest:%B %Y} Rental Report lists the highest and lowest moving annual "
        "median rents for 2-bedroom flats and 3-bedroom houses, metro and regional. "
        f"**{int(recon['matches'].sum())} of {len(recon)}** entries match the parsed value exactly, and "
        f"**{int(recon['rank_ok'].sum())} of {len(recon)}** are confirmed as top/bottom of their group "
        "against every suburb not listed.",
        "",
        "<details><summary>All Table 4 entries</summary>",
        "",
        md(recon[["dwelling", "metro", "side", "suburb", "published_median", "median_rent", "matches", "rank_ok"]]),
        "",
        "</details>",
        "",
        "## Internal totals",
        "",
        f"- **Suburb group totals.** Compared in {groups['compared']:,} region-quarters: the Group Total equals "
        f"the sum of its suburbs in {groups['equal']:,} ({100 * groups['equal'] / groups['compared']:.1f}%) "
        f"and is never below it. All {groups['gap_with_suppressed_suburb']:,} gaps occur where at least one "
        "suburb's figure is suppressed, so the total includes leases that aren't published suburb by suburb "
        f"(largest gap: {100 * groups['largest_gap_share']:.1f}% of the total). Use Group Total rows for "
        "region-level counts, not a sum of suburbs.",
        f"- **LGA totals.** The Victoria row equals the sum of the regional Group Totals in all "
        f"{lga_tot['quarters']} dwelling-quarters. It equals the sum of the published LGAs in only "
        f"{lga_tot['victoria_eq_lga_sum']}: as with suburbs, suppressed LGAs count towards the totals "
        "(every gap has at least one suppressed LGA). The workbook repeats Victoria as Metro + Non-Metro, "
        "which matches in "
        f"{lga_tot['victoria_eq_metro_plus_non_metro']} and is off by at most "
        f"{lga_tot['max_abs_gap_metro_split']:.0f} letting in the rest; the repeat is dropped.",
        f"- **Affordability totals.** The Victoria row equals the sum of the LGAs in all {aff_tot['quarters']} "
        "dwelling-quarters. The repeated total at the bottom of each sheet (Metro + Non-Metro) differs by at "
        "most 2 lettings or 0.001 of a share (rounding) and is dropped.",
        "",
        "## Plausibility",
        "",
        "| Check | Value |",
        "|---|---|",
        *[f"| {k} | {v:g} |" for k, v in plaus.items()],
        "",
        f"The smallest published count is {plaus['suburb_smallest_published_lettings']:.0f} leases in the "
        f"suburb series and {plaus['lga_smallest_published_lettings']:.0f} in the LGA series, which suggests "
        "figures are suppressed below 10 (suburbs) / 5 (LGAs). The workbooks don't state the rule.",
        "",
        f"**Large quarter-on-quarter moves.** A 12-month moving median should move slowly. Where both "
        f"quarters have at least {audit.JUMP_MIN_LETTINGS} leases, {len(jumps)} moves exceed "
        f"{audit.JUMP_THRESHOLD:.0%} (the largest move is {largest_move:.1%}). Allowing series down to 10 "
        f"leases, {len(small_jumps)} moves exceed {audit.JUMP_THRESHOLD:.0%}: small series are jumpy, so the "
        "analysis needs a minimum lease count before it ranks growth. The biggest ones:",
        "",
    ]
    if len(jumps):
        lines += [md(fmt_jumps(jumps)), ""]
    lines += [md(fmt_jumps(small_jumps.head(10))), ""]
    lines += [
        "## Name fixes",
        "",
        "Spellings that differ between workbooks or are typos in the source, mapped so the tables join:",
        "",
        "| As written | Used |",
        "|---|---|",
        *[f"| {k} | {v} |" for k, v in fixes.items()],
        "",
    ]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}")
    for name, ok in hard.items():
        print(f"  {'pass' if ok else 'FAIL'}  {name}")
    if not all(hard.values()):
        raise SystemExit("audit failed")


if __name__ == "__main__":
    main()
